import assert from 'node:assert/strict';
import {demoProjects,defaults,readiness,delivery,lead,alerts,level,projectSchema,settingsSchema,today,days} from '../lib/model.ts';
const p={...demoProjects()[2],shipments:[],actions:[],mobilized:false,waiting:0};
assert.equal(delivery(p),null);assert.equal(lead(p),null);assert.equal(readiness({...p,required:0,ready:0}),null);
assert.equal(level({...p,required:0,ready:0},defaults),1);
assert.equal(level({...p,actual:50,planned:60},defaults),3);
assert.equal(level({...p,actual:55,planned:60},defaults),2);
assert.equal(level({...p,mobilized:true,ready:23},defaults),3);
const ship={id:'one',name:'MDU',mode:'Udara',dispatch:'2026-10-01',target:'2026-10-05',arrival:'',note:''};
assert.equal(delivery({...p,shipments:[ship]},'2026-10-06'),0);
assert.equal(delivery({...p,shipments:[ship]},'2026-10-04'),null);
assert.equal(delivery({...p,shipments:[{...ship,arrival:'2026-10-05'}]},'2026-10-06'),100);
assert.equal(lead({...p,shipments:[{...ship,arrival:'2026-10-05'}]}),4);
assert(alerts({...p,shipments:[ship]},defaults,'2026-10-12').some(a=>a.level===3&&a.pa==='PA-07'));
assert(!projectSchema.safeParse({...p,ready:p.required+1}).success);
assert(!projectSchema.safeParse({...p,end:'2020-01-01'}).success);
assert(!projectSchema.safeParse({...p,reportDate:'2026-02-30'}).success);
assert(!settingsSchema.safeParse({...defaults,readyRed:100}).success);
assert.equal(days('2026-10-05','2026-10-01'),4);
assert(demoProjects().every(x=>projectSchema.safeParse(x).success));
console.log('18 indicator, boundary, and validation checks passed.');
